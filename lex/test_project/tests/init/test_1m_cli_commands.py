# 1.102 — Generated file set parity
# ---------------------------------------------------------------------
class TestCluster01m_RunFileSetParity(TestCase):
    """Every ``.run/*.run.xml`` declared by ``generate_pycharm_configs``
    is on disk after a fresh scaffold — no orphans, no missing files.

    This is the canary for "I removed Test_Audit from the source dict
    but the constant on disk still has it" drift.
    """

    EXPECTED_FILES = frozenset({
        "Init.run.xml",
        "Setup_With_AI.run.xml",
        "Start.run.xml",
        "Flower.run.xml",
        "Celery_Worker.run.xml",
        "Make_migrations.run.xml",
        "Migrate.run.xml",
        "Streamlit.run.xml",
        "Create_DB.run.xml",
        "Flush_DB.run.xml",
    })

    def test_1_102_scaffold_produces_complete_run_file_set(self):
        """1.102: scaffolding writes every expected ``.run.xml`` and
        nothing extra. Operators see the same PyCharm tray on every
        machine.
        """
        with TemporaryDirectory() as tmp:
            run_dir = _scaffold_run_dir(Path(tmp))
            on_disk = {p.name for p in run_dir.glob("*.run.xml")}

        self.assertEqual(
            on_disk, self.EXPECTED_FILES,
            f"\n  missing: {self.EXPECTED_FILES - on_disk}"
            f"\n  unexpected: {on_disk - self.EXPECTED_FILES}",
        )


# ---------------------------------------------------------------------
# 1.103 — Every .run file invokes the `lex` CLI
# ---------------------------------------------------------------------
class TestCluster01m_RunFileScriptName(TestCase):
    """All ``.run/*.run.xml`` set ``SCRIPT_NAME=lex`` — they invoke
    our CLI, not a stray ``manage.py`` or system Python.
    """

    def test_1_103_every_run_xml_uses_lex_script(self):
        """1.103: ``SCRIPT_NAME`` is ``lex`` for every generated file.

        Regression guard: a copy-paste of a different SCRIPT_NAME
        would silently bypass the CLI's setup logic (env handling,
        Django bootstrap, etc.) and fail in surprising ways.
        """
        with TemporaryDirectory() as tmp:
            run_dir = _scaffold_run_dir(Path(tmp))
            for run_file in sorted(run_dir.glob("*.run.xml")):
                parsed = _parse_run_file(run_file)
                self.assertEqual(
                    parsed.get("SCRIPT_NAME"), "lex",
                    f"{run_file.name}: SCRIPT_NAME must be 'lex'; "
                    f"got {parsed.get('SCRIPT_NAME')!r}.",
                )


# ---------------------------------------------------------------------
# 1.104 — Subcommand resolution
# ---------------------------------------------------------------------
class TestCluster01m_RunFileSubcommandResolution(TestCase):
    """The first token of every ``.run`` file's PARAMETERS must
    resolve to a real subcommand on the ``lex`` Click group, OR to
    a Django management command that the CLI's dynamic-forwarding
    layer will register.
    """

    @classmethod
    def setUpClass(cls):
        super().setUpClass()
        # Explicit @lex.command names attached at module import time.
        cls.explicit_commands = set(lex.commands.keys())

        # Django management commands — bootstrap once for the class.
        from lex.bin.lex import _bootstrap_django

        get_commands, _ = _bootstrap_django()
        cls.django_commands = set(get_commands().keys())

    def _assert_subcommand_exists(self, subcommand: str, source: str) -> None:
        if subcommand in self.explicit_commands:
            return
        if subcommand in self.django_commands:
            return
        self.fail(
            f"{source}: subcommand {subcommand!r} is neither an "
            f"explicit `lex` Click command nor a registered Django "
            f"management command. Either add it to lex/bin/lex.py "
            f"as @lex.command(name={subcommand!r}) or remove the "
            f".run.xml entry that references it.\n"
            f"  Known explicit commands: {sorted(self.explicit_commands)}\n"
            f"  (Django command count: {len(self.django_commands)})"
        )

    def test_1_104_every_run_subcommand_resolves(self):
        """1.104: every ``.run.xml`` first-token is a real subcommand.

        This is the cross-file contract that nothing else asserts:
        ``generate_pycharm_configs.py`` (declares the .run files)
        and ``lex/bin/lex.py`` (declares the CLI) must stay in sync.
        """
        with TemporaryDirectory() as tmp:
            run_dir = _scaffold_run_dir(Path(tmp))
            for run_file in sorted(run_dir.glob("*.run.xml")):
                parsed = _parse_run_file(run_file)
                first = _first_token(parsed.get("PARAMETERS", ""))
                self.assertTrue(
                    first,
                    f"{run_file.name}: PARAMETERS is empty "
                    f"({parsed.get('PARAMETERS')!r}) — every .run "
                    "must invoke at least one subcommand.",
                )
                self._assert_subcommand_exists(first, run_file.name)


