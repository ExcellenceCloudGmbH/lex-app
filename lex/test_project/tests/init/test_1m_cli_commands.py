# 1.109 — Django commands referenced by .run files
# ---------------------------------------------------------------------
class TestCluster01m_DjangoSideContract(TestCase):
    """Every ``.run`` file that delegates to a Django management
    command (``init``, ``migrate``, ``makemigrations``, ``flush``,
    ``test``, ``create_db``) must point at a name Django actually
    knows about — otherwise the CLI's dynamic forwarding falls
    through to ``execute_from_command_line`` which fails with a
    less-helpful error.
    """

    DJANGO_DELEGATED_COMMANDS = frozenset({
        "init",          # Init.run.xml
        "migrate",       # Migrate.run.xml
        "makemigrations",  # Make_migrations.run.xml
        "flush",         # Flush_DB.run.xml
        "test",          # Test_*.run.xml
        "create_db",     # Create_DB.run.xml
    })

    def test_1_109_every_delegated_command_is_a_real_django_command(self):
        """1.109: every Django-side subcommand a ``.run.xml`` references
        is registered with Django's command loader."""
        from lex.bin.lex import _bootstrap_django

        get_commands, _ = _bootstrap_django()
        registered = set(get_commands().keys())
        missing = self.DJANGO_DELEGATED_COMMANDS - registered
        self.assertFalse(
            missing,
            f"PyCharm .run files reference Django commands that are "
            f"not registered: {sorted(missing)}.\n"
            f"  Either add them under "
            f"`lex/lex_app/management/commands/` or update "
            f"`generate_pycharm_configs.py` to stop referencing them.",
        )


