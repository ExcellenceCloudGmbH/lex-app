# 1.107 — `lex --help` invocability
# ---------------------------------------------------------------------
class TestCluster01m_HelpInvocability(TestCase):
    """Every explicit subcommand answers ``--help`` cleanly via the
    in-process Click runner. This is the cheapest possible "the
    command actually exists" assertion.

    We deliberately do NOT exec ``--help`` for dynamic Django
    commands (they would trigger Django setup and be slow); 1.108
    covers that side via ``django.core.management.get_commands``.
    """

    EXPECTED_EXPLICIT_COMMANDS = EXPLICIT_COMMANDS

    def test_1_107_lex_root_help_lists_explicit_commands(self):
        """1.107: ``lex --help`` exits 0 and names every explicit command
        an operator is meant to type.

        Deprecated spellings (``HIDDEN_ALIASES``) are excluded: they stay
        runnable — 1.108 proves that — but ``hidden=True`` keeps them out
        of the listing so the help advertises one spelling per command.
        """
        runner = CliRunner()
        result = runner.invoke(lex, ["--help"])
        self.assertEqual(
            result.exit_code, 0,
            f"`lex --help` failed: exit={result.exit_code}\n"
            f"output: {result.output}",
        )
        for name in self.EXPECTED_EXPLICIT_COMMANDS - HIDDEN_ALIASES:
            self.assertIn(
                name, result.output,
                f"`lex --help` does not mention {name!r}.",
            )

    def test_1_107b_deprecated_aliases_stay_out_of_root_help(self):
        """1.107b: hidden aliases still run but are not advertised.

        Listing the same command twice under two spellings is exactly the
        ambiguity the canonical hyphenated names exist to remove. Resolution,
        not registration: the group normalises the separator now, where each
        alias used to be a second ``hidden=True`` command duplicating the whole
        option block.
        """
        import click

        runner = CliRunner()
        result = runner.invoke(lex, ["--help"])
        ctx = click.Context(lex)
        for name in HIDDEN_ALIASES:
            with self.subTest(command=name):
                self.assertIsNotNone(
                    lex.get_command(ctx, name),
                    f"deprecated alias {name!r} no longer resolves — "
                    f"drop it from HIDDEN_ALIASES if the spelling was retired "
                    f"on purpose.",
                )
                self.assertNotIn(
                    name, result.output,
                    f"`lex --help` lists the deprecated spelling {name!r}.",
                )

    def test_1_107c_delegated_commands_are_listed_and_runnable(self):
        """1.107c: what lex-mcp-local provides shows up in `lex --help`.

        The other half of the delegation. lex-app registers none of these, so
        nothing in its own source would fail if the group stopped resolving
        them -- `lex ai-verify` would simply become "No such command" at a
        customer, with `lex --help` quietly one section shorter.
        """
        import click

        delegated = _delegated_commands()
        if delegated is None:
            self.skipTest("needs lex-mcp-local installed or on the path")

        self.assertTrue(delegated, "lex-mcp-local registered no commands")
        runner = CliRunner()
        result = runner.invoke(lex, ["--help"])
        ctx = click.Context(lex)
        for name in delegated:
            with self.subTest(command=name):
                self.assertNotIn(
                    name, lex.commands,
                    f"{name!r} is registered in lex-app after all; it is "
                    f"supposed to come from lex-mcp-local.",
                )
                self.assertIsNotNone(lex.get_command(ctx, name))
                self.assertIn(name, result.output)
                self.assertEqual(
                    runner.invoke(lex, [name, "--help"]).exit_code, 0,
                    f"`lex {name} --help` did not exit 0.",
                )

    def test_1_108_each_explicit_subcommand_help_exits_zero(self):
        """1.108: ``lex <cmd> --help`` exits 0 for every explicit handler.

        Catches Click decorator typos / signature regressions that
        ``--help`` surfaces but a "real" run wouldn't because the
        handler bails earlier.
        """
        runner = CliRunner()
        for name in self.EXPECTED_EXPLICIT_COMMANDS:
            with self.subTest(command=name):
                result = runner.invoke(lex, [name, "--help"])
                self.assertEqual(
                    result.exit_code, 0,
                    f"`lex {name} --help` failed: exit={result.exit_code}\n"
                    f"output: {result.output}\n"
                    f"exception: {result.exception!r}",
                )


