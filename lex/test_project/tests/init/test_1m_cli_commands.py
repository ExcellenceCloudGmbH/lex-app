"""
Cluster 1m: ``lex`` CLI commands — every ``.run/*.run.xml`` invocation must wire through.

Intent
------

``lex setup`` scaffolds 14 PyCharm run configurations under ``.run/``.
Each one invokes the ``lex`` CLI with a specific subcommand. The
contract this test enforces is the most operator-visible one in the
framework:

    Every ``.run/*.run.xml`` file generated by
    ``generate_pycharm_configs`` must reference a subcommand that
    actually resolves through the ``lex`` CLI — either as an explicit
    ``@lex.command(...)`` Click handler or as a Django management
    command that ``_install_dynamic_commands()`` will register.

Sub-cluster 1a (`test_1a_lex_setup.py`) only checks three of the
fourteen files (Init / Start / Streamlit). The CLI helper-tests in
``lex/tests/unit/cli/test_lex_cli.py`` validate individual builders
(Celery, Flower, MCP) but never assert the cross-file contract that
"every command an operator can click in PyCharm actually works".

This sub-cluster closes that gap. We:

* parse every generated ``.run.xml`` for its ``SCRIPT_NAME`` +
  ``PARAMETERS`` pair,
* take the first token of the parameter string (the subcommand),
* assert the subcommand is reachable via the in-process Click group
  OR is a registered Django management command,
* pin the explicit ``@lex.command`` registry so any rename without a
  matching ``.run.xml`` update fails here, not in the operator's
  PyCharm.

All scenarios are **fast** (no subprocess, no real server). Click's
``CliRunner`` invokes the group in-process; Django bootstrap runs
once per class.

Scenario numbering extends ``docs/test-plan/test-clusters.md`` —
sub-cluster 1m picks up at **1.102**.
"""

from __future__ import annotations

import re
import shlex
import unittest
from pathlib import Path
from tempfile import TemporaryDirectory
from unittest import TestCase

from click.testing import CliRunner
from generate_pycharm_configs import generate_pycharm_configs
from lex.bin.lex import _SKIP_BOOTSTRAP_COMMANDS, lex

import pytest

pytestmark = pytest.mark.init

# Explicit ``@lex.command(...)`` names the framework depends on. Pinned
# here so a rename that leaves a ``.run.xml`` (or the docs) behind fails
# in CI rather than in the operator's PyCharm.
#
# The ``ai-*`` commands are no longer among them, bar one. Their options ship
# with lex-mcp-local so that adding a command does not need a lex-app release,
# and ``lex`` resolves them against the installed package rather than
# registering them here — see ``_LexGroup`` in ``lex/bin/lex.py``. They are
# covered below, derived from that package rather than pinned here, because a
# roster restated in this file is exactly what the move was getting rid of.
#
# ``ai-update`` stays: it is a bootstrap that must run before lex-mcp-local
# exists, and it is the recovery path when the installed one is too old.
EXPLICIT_COMMANDS = frozenset({
    "celery",
    "celery-workers",
    "flower",
    "streamlit",
    "start",
    "setup",
    "setup-with-ai",
    "ai-update",
})

# Deprecated spellings kept runnable for people following older docs and
# support macros, but kept out of ``lex --help`` so it advertises one spelling
# per command. They used to be a second ``hidden=True`` click command each,
# duplicating the whole option block; the group now normalises the separator,
# so these resolve rather than being registered.
HIDDEN_ALIASES = frozenset({
    "ai_issue_report",
    "ai_verify",
})


def _delegated_commands():
    """The ``ai-*`` names the installed lex-mcp-local provides, or ``None``.

    Derived, never restated. lex-app deliberately does not know this list --
    that is the whole point of delegating -- so the test reads it from the same
    registry the CLI does.
    """
    try:
        from lex_mcp.cli import command_names
    except ImportError:
        return None
    return frozenset(command_names())

# ---------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------
# Regex: extract value="..." for a named option in a .run.xml file.
_OPTION_RE = re.compile(
    r'<option\s+name="(?P<key>SCRIPT_NAME|PARAMETERS)"\s+value="(?P<val>[^"]*)"'
)


def _parse_run_file(path: Path) -> dict:
    """Pull out SCRIPT_NAME + PARAMETERS from a ``.run.xml``."""
    out = {}
    for match in _OPTION_RE.finditer(path.read_text(encoding="utf-8")):
        out[match.group("key")] = match.group("val")
    return out


def _first_token(parameters: str) -> str:
    """First whitespace-delimited token, ignoring any quoted-prompt prefix."""
    if not parameters:
        return ""
    # ``shlex.split`` handles the ``$Prompt:Test label:lex.tests$`` form
    # as a single token starting with ``$``; we only need the first
    # token regardless.
    try:
        tokens = shlex.split(parameters, posix=True)
    except ValueError:
        # Fall back to whitespace split for malformed quote pairs.
        tokens = parameters.split()
    return tokens[0] if tokens else ""


def _scaffold_run_dir(workdir: Path) -> Path:
    """Run ``generate_pycharm_configs`` into ``workdir`` and return ``.run/``."""
    (workdir / "pyproject.toml").write_text(
        "[project]\nname='cli-contract-test'\n",
        encoding="utf-8",
    )
    generate_pycharm_configs(str(workdir))
    return workdir / ".run"


