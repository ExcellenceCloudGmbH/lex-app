# 1.105 — Explicit Click registry
# ---------------------------------------------------------------------
class TestCluster01m_ExplicitClickCommands(TestCase):
    """Pin the set of explicit ``@lex.command(...)`` registrations.

    Removing or renaming one of these is what would silently break a
    ``.run.xml``; we want a hard failure here so the maintainer
    sees the breakage at the CLI source-file level.
    """

    EXPECTED_EXPLICIT_COMMANDS = EXPLICIT_COMMANDS

    def test_1_105_explicit_commands_are_all_registered(self):
        """1.105: every explicit Click handler we depend on is on the group."""
        registered = set(lex.commands.keys())
        missing = self.EXPECTED_EXPLICIT_COMMANDS - registered
        self.assertFalse(
            missing,
            f"`lex` Click group is missing explicit commands: {sorted(missing)}\n"
            f"  Registered: {sorted(registered)}",
        )

    def test_1_106_skip_bootstrap_set_matches_explicit_handlers(self):
        """1.106: the ``_SKIP_BOOTSTRAP_COMMANDS`` allow-list is a subset
        of the explicit commands.

        ``main()`` reads this set to decide whether to invoke
        ``django.setup()``. Listing a name here that isn't actually
        a Click handler would silently fall through to the dynamic
        path — same drift class as the .run/lex contract above.
        """
        registered = set(lex.commands.keys())
        leaked = _SKIP_BOOTSTRAP_COMMANDS - registered
        self.assertFalse(
            leaked,
            f"_SKIP_BOOTSTRAP_COMMANDS contains names that aren't "
            f"explicit Click handlers: {sorted(leaked)}",
        )


