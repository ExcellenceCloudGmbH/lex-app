#### Note: Messages shall be delivered in the following format: "Severity: Message" The colon and the whitespace after are required for the code to work correctly ####
# Severity could be something like 'Error', 'Warning', 'Caution', etc. (See Static variables below!)


class CalculationLog(models.Model):
    modification_restriction = AdminReportsModificationRestriction()
    id = models.AutoField(primary_key=True)
    timestamp = models.DateTimeField(auto_now_add=True)
    calculationId = models.TextField(default="test_id", db_index=True)
    calculation_log = models.TextField(default="")
    parent_log = models.ForeignKey(
        "self",
        on_delete=models.CASCADE,
        null=True,
        blank=True,
        related_name="parent_logs",
    )  # parent calculation log
    audit_log = models.ForeignKey(
        "audit_logging.AuditLog", on_delete=models.CASCADE, null=True, blank=True
    )
    # Generic fields to reference any calculatable object:
    # If you want to allow CalculationLog entries without a related instance,
    # consider setting null=True and blank=True. Otherwise, ensure an instance is always found.
    content_type = models.ForeignKey(
        ContentType, on_delete=models.CASCADE, null=True, blank=True
    )
    object_id = models.PositiveIntegerField(null=True, blank=True)
    # This generic foreign key ties the above two fields, allowing dynamic reference.
    calculatable_object = GenericForeignKey("content_type", "object_id")
    # Title of an object-less section node (``model_logging_context("...")``).
    # Heading rows carry the title here and leave content_type/object_id NULL;
    # model-backed rows leave this NULL.
    heading = models.TextField(null=True, blank=True)

    # Severities – to be concatenated with the message in the create statement
    SUCCESS = "Success: "
    WARNING = "Warning: "
    ERROR = "Error: "
    START = "Start: "
    FINISH = "Finish: "

    # Message types
    PROGRESS = "Progress"
    INPUT = "Input Validation"
    OUTPUT = "Output Validation"

    class Meta:
        app_label = "audit_logging"

    def __str__(self):
        # Heading nodes show their section title in the log tree. Model-backed
        # nodes keep Django's default string, which the frontend recognizes
        # and relabels ("Consolidated log" / "Section N").
        if self.heading:
            return self.heading
        return f"CalculationLog object ({self.pk})"

    @classmethod
    def _find_first(cls, logger, **lookup_kwargs):
        existing_entries = list(
            cls.objects.filter(**lookup_kwargs).order_by("id")[:2]
        )
        if not existing_entries:
            return None
        if len(existing_entries) > 1:
            logger.warning(
                "Detected duplicate CalculationLog rows for %s; using id=%s.",
                lookup_kwargs,
                existing_entries[0].id,
            )
        return existing_entries[0]

    @classmethod
    def _get_or_create_locked(cls, logger, **lookup_kwargs):
        existing = cls._find_first(logger, **lookup_kwargs)
        if existing is not None:
            return existing, False

        return cls.objects.create(**lookup_kwargs), True

    @classmethod
    def _ensure_heading_node(cls, frame, parent_node, context_info, logger):
        """
        Get-or-create the row for a LogHeading frame, lazily on first log.

        The pk is cached on the frame so subsequent log calls inside the same
        with-block skip the lookup. Keyed by (calculationId, audit_log,
        heading, parent_log): the same title under two different parents is
        two nodes, while re-entering the same heading under the same parent
        reuses one node.
        """
        if frame.node_id:
            node = cls.objects.filter(pk=frame.node_id).first()
            if node is not None:
                return node
        node, _ = cls._get_or_create_locked(
            logger,
            calculationId=context_info.calculation_id,
            audit_log=context_info.audit_log,
            content_type=None,
            object_id=None,
            heading=frame.title,
            parent_log=parent_node,
        )
        frame.node_id = node.pk
        return node

    # A model is usually calculated before its first save: a row generated by
    # ``create()`` has no primary key while its ``calculate()`` logs. Its log
    # row then cannot be found by object_id, and a lookup on object_id NULL
    # would hand it a sibling's row. So the first line written for an unsaved
    # model creates a row of its own, and the row's pk is kept on the
    # instance, per calculation, under UNSAVED_ROWS_ATTR. Every later line -
    # its own, and those of the models nested under it - goes through the
    # instance, and the row gets its object_id once the model is saved.
    # Deferred writes (``log`` inside a transaction runs on commit) normally
    # see the pk already and never need this.
    UNSAVED_ROWS_ATTR = UNSAVED_ROWS_ATTR

    @classmethod
    def _kept_row(cls, model, calculation_id):
        """The row kept on an unsaved ``model`` for this calculation, or ``None``.

        Gives the row its object_id when ``model`` has been saved since, so a
        lookup by object_id finds the same row from then on.
        """
        rows = getattr(model, cls.UNSAVED_ROWS_ATTR, None)
        row_id = rows.get(calculation_id) if rows else None
        if row_id is None:
            return None
        row = cls.objects.filter(pk=row_id).first()
        if row is None:
            # Rolled back with the transaction that wrote it.
            return None
        if row.object_id is None and getattr(model, "pk", None) is not None:
            row.object_id = model.pk
            row.save(update_fields=["object_id"])
        return row

    @classmethod
    def _keep_row(cls, model, calculation_id, row):
        rows = getattr(model, cls.UNSAVED_ROWS_ATTR, None)
        if rows is None:
            rows = {}
            setattr(model, cls.UNSAVED_ROWS_ATTR, rows)
        rows[calculation_id] = row.pk

    @classmethod
    def claim_rows(cls, model):
        """Give the rows ``model`` was logged into before it was saved its object_id.

        Called when a model's ``model_logging_context`` block ends. Does
        nothing while the model is still unsaved. Never raises: the block may
        be ending because of an exception, which must not be replaced.
        """
        rows = getattr(model, cls.UNSAVED_ROWS_ATTR, None)
        pk = getattr(model, "pk", None)
        if not rows or pk is None:
            return
        try:
            cls.objects.filter(
                pk__in=list(rows.values()), object_id__isnull=True
            ).update(object_id=pk)
        except Exception:
            logging.getLogger("lex.calclog").warning(
                "Could not link the calculation log of %r to its record",
                model,
                exc_info=True,
            )

    @classmethod
    def prepare_for_dispatch(cls, frames):
        """Create the rows of the unsaved models in ``frames`` before they are copied.

        A Celery task receives a copy of the model context stack. An unsaved
        model is found only through the row kept on the instance, so a copy
        taken before that row exists cannot find it: every worker would create
        a row of its own for the same model, and none of them would get its
        object_id. Creating the rows first makes the copies carry them. A
        model that nothing is logged under afterwards keeps an empty row.

        Does nothing when every model in ``frames`` is saved or no calculation
        is running. Never raises.
        """
        from lex.api.utils import operation_context
        from lex.audit_logging.utils.ModelContext import LogHeading

        calculation_id = (operation_context.get() or {}).get("calculation_id")
        if not calculation_id:
            return
        frames = list(frames or [])
        # Checked without the database: a fan-out dispatches once per group,
        # and only the first dispatch has rows to create.
        unsaved = [
            index
            for index, frame in enumerate(frames)
            if not isinstance(frame, LogHeading)
            and getattr(frame, "pk", None) is None
            and not (getattr(frame, cls.UNSAVED_ROWS_ATTR, None) or {}).get(calculation_id)
        ]
        if not unsaved:
            return
        logger = logging.getLogger("lex.calclog")
        try:
            from lex.audit_logging.utils.ContextResolver import ContextResolver

            try:
                context_info = ContextResolver.resolve()
            except ContextResolutionError:
                return
            with transaction.atomic():
                cls._lock_audit_log(context_info)
                for index in unsaved:
                    if cls._kept_row(frames[index], context_info.calculation_id) is None:
                        cls._row_for_frames(frames[: index + 1], context_info, logger)
        except Exception:
            logger.warning(
                "Could not create the calculation log rows of unsaved models before dispatch",
                exc_info=True,
            )

    @staticmethod
    def _lock_audit_log(context_info):
        audit_log_id = getattr(context_info.audit_log, "pk", None)
        if audit_log_id:
            from lex.audit_logging.models.AuditLog import AuditLog

            AuditLog.objects.select_for_update().get(pk=audit_log_id)

    @staticmethod
    def _frame_content_type(frame, context_info):
        # The resolver has already looked up the top frame and its parent.
        if frame is context_info.current_model and context_info.content_type is not None:
            return context_info.content_type
        if frame is context_info.parent_model and context_info.parent_content_type is not None:
            return context_info.parent_content_type
        from lex.audit_logging.utils.content_types import safe_get_content_type

        try:
            return safe_get_content_type(frame)
        except Exception:
            return None

    @classmethod
    def _row_for_frames(cls, frames, context_info, logger):
        """The row the top frame of ``frames`` writes to, and its parent row.

        Creates whatever does not exist yet. The row hangs off the row of the
        nearest model frame below the top, with the heading frames in between
        chained off that row (or off nothing when no model is below them).
        """
        from lex.audit_logging.utils.ModelContext import LogHeading

        top = frames[-1] if frames else None
        parent_index = next(
            (
                index
                for index in range(len(frames) - 2, -1, -1)
                if not isinstance(frames[index], LogHeading)
            ),
            None,
        )
        parent_log = None
        if parent_index is not None:
            parent_log = cls._parent_row(frames[: parent_index + 1], context_info, logger)
        first_heading = 0 if parent_index is None else parent_index + 1
        for heading_frame in frames[first_heading:-1]:
            parent_log = cls._ensure_heading_node(
                heading_frame, parent_log, context_info, logger
            )
        if isinstance(top, LogHeading):
            return cls._ensure_heading_node(top, parent_log, context_info, logger), parent_log
        return cls._model_row(top, parent_log, context_info, logger), parent_log

    @classmethod
    def _parent_row(cls, frames, context_info, logger):
        """The row of ``frames[-1]``, a model, as the parent of what is above it.

        A parent nothing has been logged for yet - a model that logs only
        after its children, or never - gets its row now, where its own first
        line would have put it: under its own parent. Created detached, it
        would show up as a second root, and the parent's own lines would
        later open another row beside it.
        """
        parent = frames[-1]
        kept = cls._kept_row(parent, context_info.calculation_id)
        if kept is not None:
            return kept
        if getattr(parent, "pk", None) is not None:
            content_type = cls._frame_content_type(parent, context_info)
            if content_type is None:
                return None
            existing = cls._find_first(
                logger,
                calculationId=context_info.calculation_id,
                audit_log=context_info.audit_log,
                content_type=content_type,
                object_id=parent.pk,
            )
            if existing is not None:
                return existing
        # An unsaved parent's row is also kept on the instance (_model_row).
        row, _ = cls._row_for_frames(frames, context_info, logger)
        return row

    @classmethod
    def _model_row(cls, model, parent_log, context_info, logger):
        """The row a model frame's own lines go to."""
        if model is not None:
            kept = cls._kept_row(model, context_info.calculation_id)
            if kept is not None:
                return kept
        lookup = {
            "calculationId": context_info.calculation_id,
            "audit_log": context_info.audit_log,
            "content_type": (
                cls._frame_content_type(model, context_info) if model is not None else None
            ),
            "parent_log": parent_log,
            # heading=None keeps object-less model lookups (content_type and
            # object_id both NULL) from ever matching a heading row.
            "heading": None,
        }
        if model is not None and model.pk is None:
            row = cls.objects.create(object_id=None, **lookup)
            cls._keep_row(model, context_info.calculation_id, row)
            return row
        row, _ = cls._get_or_create_locked(
            logger, object_id=model.pk if model is not None else None, **lookup
        )
        return row

    @classmethod
    def _persist_message(cls, context_info, message: str, logger):
        frames = context_info.frames
        if frames is None:
            frames = [
                model
                for model in (context_info.parent_model, context_info.current_model)
                if model is not None
            ]

        with transaction.atomic():
            cls._lock_audit_log(context_info)
            log_entry, parent_log = cls._row_for_frames(list(frames), context_info, logger)

            logger.debug(
                f"Log: {{'calc_id': {context_info.calculation_id!r}, 'row': {log_entry.pk}, "
                f"'content_type': {log_entry.content_type}, 'object_id': {log_entry.object_id}, "
                f"'heading': {log_entry.heading!r}}}"
            )
            logger.debug(f"Parent: {getattr(parent_log, 'pk', None)}")
            log_entry.calculation_log = (log_entry.calculation_log or "") + f"\n{message}"
            log_entry.save(update_fields=["calculation_log"])

    @classmethod
    def keep_rolled_back_log(cls, calculation_id, root_record, root_instance) -> bool:
        """
        Keep what a failed run logged when its transaction took the rows with it.

        `log` persists on commit, so a calculation that fails inside its
        transaction — every `is_atomic` model — is rolled back with every row it
        wrote: the steps that succeeded vanish with the one that failed. The live
        cache is not transactional. It holds the run's whole log, in order, under
        the root's key until the run ends, so the failure paths call this just
        before they purge it, and it writes that text back as the run's log: one
        row on the root record, the same text the live stream showed.

        Does nothing when rows for the run survived (a run outside a transaction
        keeps them) or when the cache holds nothing for it. Never raises — a
        failure path must not fail again on its way to reporting the first one.
        """
        logger = logging.getLogger("lex.calclog")
        try:
            if not calculation_id or not root_record or root_instance is None:
                return False
            if cls.objects.filter(calculationId=calculation_id).exists():
                return False
            text = CacheManager.get_message(
                CacheManager.build_cache_key(root_record, calculation_id)
            )
            if not text:
                return False

            from lex.audit_logging.models.AuditLog import AuditLog

            # The run's first audit row was written by the request that started
            # it, before the transaction, so it survived; rows the calculation
            # wrote itself went with the rollback.
            audit_log = (
                AuditLog.objects.filter(calculation_id=calculation_id).order_by("id").first()
            )
            cls.objects.create(
                calculationId=calculation_id,
                audit_log=audit_log,
                content_type=ContentType.objects.get_for_model(type(root_instance)),
                object_id=root_instance.pk,
                calculation_log=text,
            )
            return True
        except Exception:
            logger.warning(
                "Could not keep the log of failed calculation %s",
                calculation_id,
                exc_info=True,
            )
            return False

    @classmethod
    def log(cls, message: str):
        """
        Logs `message` against the current model context.
        
        This method has been refactored to use helper classes for better organization
        and error handling while maintaining full backward compatibility.
        
        Args:
            message: The log message to record
        """

        logger = logging.getLogger("lex.calclog")
        try:
            # 1) Resolve context using ContextResolver

            from lex.audit_logging.utils.ContextResolver import ContextResolver
            context_info = ContextResolver.resolve()
            # logger.warning(f"Context: {context_info}")


            parent_debug = None
            log_debug = None



            # 2) Create parent log entry if needed
            db_alias = (
                getattr(getattr(context_info.audit_log, "_state", None), "db", None)
                or cls.objects.db
                or "default"
            )
            connection = transaction.get_connection(using=db_alias)

            if connection.in_atomic_block:
                def persist_after_commit():
                    try:
                        cls._persist_message(context_info, message, logger)
                    except Exception as persist_error:
                        logger.error("ERROR IN CALCULATION LOG")
                        logger.error(
                            "Unexpected deferred error in CalculationLog.log() for message: %s. Error: %s",
                            message,
                            persist_error,
                            exc_info=True,
                        )
                        logger.warning(f"Fallback logging: {message}")

                transaction.on_commit(persist_after_commit, using=db_alias)
            else:
                cls._persist_message(context_info, message, logger)


            root_record = context_info.root_record

            # logger.warning(f"The context_info from CalculationLog, context: {context_info}")
            # 6) Store in cache using CacheManager
            if context_info.current_record:
                cache_key = CacheManager.build_cache_key(
                    context_info.current_record,
                    context_info.calculation_id
                )
                CacheManager.store_message(cache_key, message)

            if context_info.root_record and context_info.root_record != context_info.current_record:
                cache_key = CacheManager.build_cache_key(
                    context_info.root_record,
                    context_info.calculation_id
                )
                CacheManager.store_message(cache_key, message)

            # 7) Log to standard logger (sends to WebSocket via WebSocketHandler)
            # Send to current record's WebSocket group
            logger.debug(
                message,
                extra={
                    "calculation_record": context_info.current_record,
                    "calculationId": context_info.calculation_id,
                },
            )

            # Also send to root record's WebSocket group so parent calculations
            # receive child logs in real-time (mirrors the cache store pattern above)
            if context_info.root_record and context_info.root_record != context_info.current_record:
                logger.debug(
                    message,
                    extra={
                        "calculation_record": context_info.root_record,
                        "calculationId": context_info.calculation_id,
                    },
                )
            
        except ContextResolutionError as e:
            # Context resolution failed (e.g. missing calculation_id in a Celery
            # worker where operation_context was not propagated).  We still want
            # real-time log streaming to work, so fall back to the model_context
            # stack for WebSocket routing — just skip DB persistence.
            logger.debug(
                f"Context resolution incomplete, using model-context fallback: {e}",
            )
            try:
                from lex.audit_logging.utils.ModelContext import _model_context as _mc
                model_ctx = _mc.get()['model_context']
                # Skip heading frames — WebSocket groups are keyed by real
                # model records, headings only shape the tree.
                current = model_ctx.get_current_model()
                root = model_ctx.get_root_model()
                current_record = f"{current._meta.model_name}_{current.pk}" if current else None
                root_record = f"{root._meta.model_name}_{root.pk}" if root else None

                # Send to WebSocket even without full context
                if current_record:
                    logger.debug(
                        message,
                        extra={
                            "calculation_record": current_record,
                            "calculationId": "",
                        },
                    )
                if root_record and root_record != current_record:
                    logger.debug(
                        message,
                        extra={
                            "calculation_record": root_record,
                            "calculationId": "",
                        },
                    )
            except Exception:
                logger.debug(f"Model-context fallback also failed for: {message}")
            
            
        except Exception as e:
            # Handle any other unexpected errors
            logger.error(f"ERROR IN CALCULATION LOG")
            logger.error(f"Log: {log_debug}")
            logger.error(f"Parent: {parent_debug}")
            logger.error(
                f"Unexpected error in CalculationLog.log() for message: {message}. Error: {str(e)}",
                exc_info=True
            )
            # Ensure the message is still logged somewhere
            logger.warning(f"Fallback logging: {message}")
